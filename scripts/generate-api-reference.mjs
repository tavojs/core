import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

const root = process.cwd();
const checkOnly = process.argv.includes("--check");
const packageFile = path.join(root, "packages/core/package.json");
const packageJson = JSON.parse(await fs.readFile(packageFile, "utf8"));
const entryPoints = Object.entries(packageJson.exports)
  .filter(([, value]) => value?.types)
  .map(([entry, value]) => ({
    packageName: entry === "." ? "@tavojs/core" : `@tavojs/core/${entry.slice(2)}`,
    file: path.resolve(path.dirname(packageFile), value.types)
  }))
  .sort((left, right) => {
    if (left.packageName === "@tavojs/core") return 1;
    if (right.packageName === "@tavojs/core") return -1;
    return left.packageName.localeCompare(right.packageName);
  });

const stabilityFile = path.join(root, "packages/core/dist/stability.js");
const { TAVO_API_STABILITY } = await import(`${pathToFileURL(stabilityFile).href}?docs=${Date.now()}`);
const missingStability = entryPoints
  .map((entry) => entry.packageName)
  .filter((packageName) => !TAVO_API_STABILITY[packageName]);
if (missingStability.length > 0) {
  throw new Error(`Missing API stability entries: ${missingStability.join(", ")}`);
}

const program = ts.createProgram({
  rootNames: entryPoints.map((entry) => entry.file),
  options: {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    skipLibCheck: true
  }
});
const checker = program.getTypeChecker();

function documentation(symbol) {
  return ts.displayPartsToString(symbol.getDocumentationComment(checker))
    .replace(/\s+/g, " ")
    .trim();
}

const candidates = new Map();
for (const entry of entryPoints) {
  const source = program.getSourceFile(entry.file);
  const moduleSymbol = source && checker.getSymbolAtLocation(source);
  if (!moduleSymbol) {
    throw new Error(`Unable to inspect declarations for ${entry.packageName}: ${entry.file}`);
  }
  for (const symbol of checker.getExportsOfModule(moduleSymbol).filter((symbol) => symbol.name !== "default")) {
    const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
    const declarations = target.declarations ?? symbol.declarations ?? [];
    const identity = declarations
      .map((declaration) => `${declaration.getSourceFile().fileName}:${declaration.pos}`)
      .sort()
      .join("|");
    const key = `${symbol.name}:${identity || symbol.name}`;
    const candidate = {
      entry,
      name: symbol.name,
      documentation: documentation(target),
      direct: declarations.some((declaration) => path.resolve(declaration.getSourceFile().fileName) === entry.file)
    };
    const current = candidates.get(key);
    if (
      !current ||
      (candidate.direct && !current.direct) ||
      (candidate.direct === current.direct &&
        current.entry.packageName === "@tavojs/core" &&
        candidate.entry.packageName !== "@tavojs/core")
    ) {
      candidates.set(key, candidate);
    }
  }
}

const sections = entryPoints
  .map((entry) => ({
    name: entry.packageName,
    stability: TAVO_API_STABILITY[entry.packageName],
    symbols: Array.from(candidates.values())
      .filter((candidate) => candidate.entry.packageName === entry.packageName)
      .map(({ name, documentation: symbolDocumentation }) => ({
        name,
        documentation: symbolDocumentation
      }))
      .sort((left, right) => left.name.localeCompare(right.name))
  }));

const lines = [
  "# API Reference",
  "",
  "<!-- Generated by npm run docs:api. Do not edit by hand. -->",
  "",
  "> Online API inventory: [tavojs.dev/docs/core/api](https://tavojs.dev/docs/core/api)",
  "",
  "This deduplicated reference is generated from the published TypeScript declarations. Each symbol appears under its canonical focused entry point; stability is read from the package contract.",
  ""
];
for (const section of sections) {
  lines.push(
    `## \`${section.name}\``,
    "",
    `**${section.stability.level} since ${section.stability.since}.** ${section.stability.note}`,
    ""
  );
  if (section.symbols.length === 0) {
    lines.push("No named exports.", "");
    continue;
  }
  for (const symbol of section.symbols) {
    lines.push(`- \`${symbol.name}\`${symbol.documentation ? ` — ${symbol.documentation}` : ""}`);
  }
  lines.push("");
}

const outputFile = path.join(root, "docs/api-reference.md");
const output = lines.join("\n").replace(/\n*$/, "\n");
if (checkOnly) {
  const current = await fs.readFile(outputFile, "utf8");
  if (current !== output) {
    throw new Error("docs/api-reference.md is stale. Run npm run docs:api.");
  }
  console.log(`Verified docs/api-reference.md (${sections.length} canonical entry points).`);
} else {
  await fs.writeFile(outputFile, output, "utf8");
  console.log(`Generated docs/api-reference.md (${sections.length} canonical entry points).`);
}
