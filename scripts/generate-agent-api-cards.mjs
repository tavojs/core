import fs from "node:fs/promises";
import path from "node:path";
import ts from "typescript";

const root = process.cwd();
const checkOnly = process.argv.includes("--check");
const entries = {
  defineRoutePage: "packages/core/dist/framework/index.d.ts",
  createTavo: "packages/core/dist/client.d.ts",
  defineGlobalStore: "packages/core/dist/framework/index.d.ts",
  defineValidatedAction: "packages/core/dist/validation.d.ts",
  Seo: "packages/core/dist/components/seo.d.ts"
};
const files = Array.from(new Set(Object.values(entries))).map((file) => path.resolve(root, file));
const program = ts.createProgram(files, { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler });
const checker = program.getTypeChecker();
const signatures = {};

for (const [name, relativeFile] of Object.entries(entries)) {
  const source = program.getSourceFile(path.resolve(root, relativeFile));
  if (!source) throw new Error(`Missing declaration entry for ${name}: ${relativeFile}`);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  const symbol = checker.getExportsOfModule(moduleSymbol).find((candidate) => candidate.name === name);
  if (!symbol) throw new Error(`Public declaration ${name} was not found in ${relativeFile}.`);
  const declaration = symbol.valueDeclaration ?? symbol.declarations?.[0];
  const type = checker.getTypeOfSymbolAtLocation(symbol, declaration ?? source);
  const calls = type.getCallSignatures();
  const rendered = calls.length > 0
    ? calls.map((signature) => checker.signatureToString(signature, declaration, ts.TypeFormatFlags.NoTruncation)).join(" | ")
    : checker.typeToString(type, declaration, ts.TypeFormatFlags.NoTruncation);
  signatures[name] = rendered.replace(/import\("[^"]+"\)\./g, "");
}

const output = [
  "// Generated by scripts/generate-agent-api-cards.mjs. Do not edit by hand.",
  `export const GENERATED_API_SIGNATURES: Record<string, string> = ${JSON.stringify(signatures, null, 2)};`,
  ""
].join("\n");
const outputFile = path.join(root, "packages/cli/src/cli/protocol/generated-api.mts");
if (checkOnly) {
  const current = await fs.readFile(outputFile, "utf8");
  if (current !== output) {
    throw new Error(
      "packages/cli/src/cli/protocol/generated-api.mts is stale. Run npm run docs:agent."
    );
  }
  console.log(`Verified ${Object.keys(signatures).length} agent API signatures.`);
} else {
  await fs.writeFile(outputFile, output, "utf8");
  console.log(`Generated ${Object.keys(signatures).length} agent API signatures.`);
}
